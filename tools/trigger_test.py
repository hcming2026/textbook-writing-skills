# 语义邻接的负例：命中关键词但应被 description 的否定边界挡住，
# 单看关键词无法判定，需人工确认边界句是否覆盖。
EDGE_NEG = {"把这一课改好", "修改错别字", "润色这段文字", "修改论文摘要", "审校这份稿",
            "出期末试卷", "生成 PDF", "做 PPT", "改错别字"}


def hits(case, keys):
    return [k for k in keys if k in case]


def main(argv):
    verbose = "-v" in argv
    total_bad = 0
    for skill, groups in CASES.items():
        text = (SKILL_DIR / skill / "SKILL.md").read_text(encoding="utf-8")
        desc = re.search(r"description:[ \t]*(.+)", text).group(1)
        keys = KEYS[skill]
        print(f"\n=== {skill} ===")

        miss = []
        for case in groups["pos"]:
            h = hits(case, keys)
            if not h:
                miss.append(case)
            if verbose:
                print(f"  [{'OK  ' if h else 'MISS'}] {case}  ← {','.join(h) or '无命中'}")

        risk = []
        for case in groups["neg"]:
            h = hits(case, keys)
            if h and case in EDGE_NEG:
                risk.append((case, h))
            elif h:
                # 负例命中非邻接词：多半是设计内的排除句（如"不含改稿"），
                # 记为观察项而非误判，避免把正常的排除句算成错误
                if verbose:
                    print(f"  [OBSV] {case}  ← {','.join(h)}（命中但非邻接，不计误判）")

        print(f"  漏触发 {len(miss)} 条，误触发风险 {len(risk)} 条")
        for c in miss:
            print(f"    漏：{c}")
        for c, h in risk:
            print(f"    误：{c}（命中 {','.join(h)}）")
        total_bad += len(miss) + len(risk)

    print(f"\n合计 {total_bad} 条，阈值 {TOLERANCE} 条 → {'通过' if total_bad <= TOLERANCE else '不通过'}")
    print("说明：'误触发风险'只统计语义邻接的负例，正常排除句不计入。")
    return 0 if total_bad <= TOLERANCE else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv))
